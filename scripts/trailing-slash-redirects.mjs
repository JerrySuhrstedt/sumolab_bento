// Appends explicit 308 rules to dist/client/_redirects so /path (no slash)
// redirects permanently to /path/ instead of Cloudflare's default 307.
// Runs as npm postbuild. One static rule per prerendered HTML directory.
// Rules are PREPENDED: static rules must sit above the splat rules in
// public/_redirects or Cloudflare stops applying later ones (verified locally).
import { readdirSync, statSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = 'dist/client';
const redirectsFile = join(root, '_redirects');
const existing = existsSync(redirectsFile) ? readFileSync(redirectsFile, 'utf8') : '';
const existingSources = new Set(
	existing.split('\n').filter((l) => l.trim() && !l.startsWith('#')).map((l) => l.trim().split(/\s+/)[0]),
);

const pages = [];
function walk(dir, url) {
	for (const name of readdirSync(dir)) {
		const full = join(dir, name);
		if (!statSync(full).isDirectory()) continue;
		if (name.startsWith('_')) continue;
		const childUrl = `${url}/${name}`;
		if (existsSync(join(full, 'index.html'))) pages.push(childUrl);
		walk(full, childUrl);
	}
}
walk(root, '');

const rules = pages.filter((p) => !existingSources.has(p)).map((p) => `${p} ${p}/ 308`);

// The old WordPress site served every article at the root (/slug/). The rebuild
// moved them under /blog/. Emit a 301 from the old root URL, with and without
// the trailing slash, for every current article, unless a real top-level page
// or a hand-written rule already owns that path.
const topLevel = new Set(pages.filter((p) => p.split('/').length === 2));
const legacy = [];
for (const p of pages) {
	const m = p.match(/^\/blog\/([^/]+)$/);
	if (!m) continue;
	const slug = m[1];
	if (topLevel.has(`/${slug}`)) continue;
	for (const src of [`/${slug}/`, `/${slug}`]) {
		if (!existingSources.has(src)) legacy.push(`${src} /blog/${slug}/ 301`);
	}
}
rules.push(...legacy);
console.log(`legacy root-to-blog redirects: ${legacy.length}`);
writeFileSync(redirectsFile, `# Generated by scripts/trailing-slash-redirects.mjs: permanent trailing-slash redirects (kept above splat rules)\n${rules.join('\n')}\n\n${existing}`);
console.log(`trailing-slash redirects: ${rules.length} rules appended to ${redirectsFile}`);
